using System.Formats.Tar;
using System.IO.Compression;
using System.Text.Json;
using VrcSetup.Core;

namespace VrcSetup.Infrastructure;

public static class UnityProjectTemplate
{
    // Unity Hub templates omit modules that the Editor normally injects during
    // project creation. Our VPM-only scaffold must perform that step itself.
    public static async Task EnsureBuiltinModulesAsync(string project, string editor, CancellationToken token = default)
    {
        var folder = Path.Combine(Path.GetDirectoryName(editor)!, "Data", "Resources", "PackageManager", "BuiltInPackages");
        var file = Path.Combine(project, "Packages", "manifest.json");
        var manifest = System.Text.Json.Nodes.JsonNode.Parse(await File.ReadAllTextAsync(file, token))!.AsObject();
        var dependencies = manifest["dependencies"]?.AsObject() ?? throw new IOException("Unity manifest dependencies are missing.");
        var modules = Directory.Exists(folder)
            ? Directory.EnumerateDirectories(folder, "com.unity.modules.*").Select(Path.GetFileName).OfType<string>().ToArray()
            : "ai androidjni animation assetbundle audio cloth director imageconversion imgui jsonserialize particlesystem physics physics2d screencapture terrain terrainphysics tilemap ui uielements unityanalytics unitywebrequest unitywebrequestassetbundle unitywebrequestaudio unitywebrequesttexture unitywebrequestwww vehicles video vr wind xr".Split(' ').Select(x => "com.unity.modules." + x).ToArray();
        var changed = false;
        foreach (var module in modules)
            if (!dependencies.ContainsKey(module)) { dependencies[module] = "1.0.0"; changed = true; }
        if (changed) await AtomicFile.WriteJsonAsync(file, manifest, token);
    }
    // Extract only source project files from Unity's installed 3D template.
    // Library/cache contents are regenerated by the final Unity import session.
    public static async Task ExtractAsync(string archive, string destination, string version, CancellationToken token)
    {
        const string prefix = "package/ProjectData~/";
        long bytes = 0; var files = 0;
        await using var stream = File.OpenRead(archive);
        await using var gzip = new GZipStream(stream, CompressionMode.Decompress);
        using var tar = new TarReader(gzip);
        while (await tar.GetNextEntryAsync(copyData: false, cancellationToken: token) is { } entry)
        {
            var name = entry.Name.Replace('\\', '/');
            if (!name.StartsWith(prefix, StringComparison.Ordinal)) continue;
            var relative = name[prefix.Length..];
            if (!(relative.StartsWith("Assets/", StringComparison.Ordinal) || relative.StartsWith("Packages/", StringComparison.Ordinal) || relative.StartsWith("ProjectSettings/", StringComparison.Ordinal))) continue;
            if (relative.Split('/').Any(x => x is "." or "..")) throw new IOException("Unity template contains an invalid path.");
            var path = Path.GetFullPath(Path.Combine(destination, relative)); ProjectRules.EnsureContained(destination, path);
            if (entry.EntryType == TarEntryType.Directory) { Directory.CreateDirectory(path); continue; }
            if (entry.EntryType is not (TarEntryType.RegularFile or TarEntryType.V7RegularFile)) throw new IOException("Unity template contains an unsupported link.");
            if (++files > 4096 || entry.Length > 128 * 1024 * 1024 || (bytes += entry.Length) > 256 * 1024 * 1024) throw new IOException("Unity template exceeds the source-file limit.");
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            await using var output = File.Create(path);
            if (entry.DataStream is { } data) await data.CopyToAsync(output, token);
        }
        var manifest = Path.Combine(destination, "Packages", "manifest.json");
        if (!File.Exists(manifest) || !Directory.Exists(Path.Combine(destination, "ProjectSettings"))) throw new IOException("Unity's 3D template is incomplete.");
        using (var json = JsonDocument.Parse(await File.ReadAllTextAsync(manifest, token)))
            if (!json.RootElement.TryGetProperty("dependencies", out var dependencies) || dependencies.ValueKind != JsonValueKind.Object) throw new IOException("Unity template manifest is invalid.");
        Directory.CreateDirectory(Path.Combine(destination, "Assets"));
        await File.WriteAllTextAsync(Path.Combine(destination, "ProjectSettings", "ProjectVersion.txt"), "m_EditorVersion: " + version + "\n", token);
    }
}

export type Language = 'system' | 'it' | 'en';
export const Locale = createContext<'it' | 'en'>('it');
export function translator(locale: 'it' | 'en') {
  return (message: string, values: Record<string, string | number> = {}) =>
    (locale === 'en' ? english[message] ?? message : message).replace(/\{(\w+)\}/g, (marker, key) => String(values[key] ?? marker));
}
export const useText = () => translator(useContext(Locale));
